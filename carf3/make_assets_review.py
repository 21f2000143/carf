# ------------------------------------------------------------------ GSE20194 (third external cohort)
def tab_gse20194():
    """Reads experiments/results/e8_gse20194/ (pre-existing, frozen, read-only; see its summary.md
    and provenance.json), evaluated with CARF v1 (B=1, gamma=0.25; no RPPA/gate/treatment anchor,
    since MRI and RPPA are absent in this cohort regardless). Not re-run by carf3."""
    if not E8.exists():
        print('experiments/results/e8_gse20194 not found; skipping GSE20194 table/macros'); return
    met = pd.read_csv(E8 / 'metrics.csv').set_index('model')
    boot = pd.read_csv(E8 / 'bootstrap.csv').set_index('model')
    prov = json.loads((E8 / 'provenance.json').read_text())
    ov = prov['overlap']
    models = ['clinical', 'mean', 'stack', 'mask_stack', 'offset_lr', 'robust_offset_lr', 'moddrop_mlp', 'carf']
    label = {'clinical': 'Clinical', 'mean': 'Mean', 'stack': 'Stacking', 'mask_stack': 'Mask-stacking',
            'offset_lr': 'Offset LR', 'robust_offset_lr': 'Robust offset LR', 'moddrop_mlp': 'ModDrop MLP',
            'carf': 'CARF (v1)'}
    rows = ['\\begin{tabular}{lccc}', '\\toprule', 'Model & AUROC & Brier & ECE \\\\', '\\midrule']
    for m in models:
        r = met.loc[m]
        rows.append(f"{label[m]} & {r.auroc:.3f} & {r.brier:.3f} & {r.ece:.3f} \\\\")
    rows += ['\\bottomrule', '\\end{tabular}']
    (GEN / 'tab_gse20194.tex').write_text('% derived from experiments/results/e8_gse20194 (read-only)\n'
                                          + '\n'.join(rows) + '\n')

    pred = pd.read_csv(E8 / 'predictions.csv', dtype={'patient_id': str}).set_index('patient_id')
    uniq = ov['gse20194_not_in_gse25066']
    sub = pred.loc[uniq]
    from sklearn.metrics import roc_auc_score
    mac('GseTwoZeroOneNineFourN', int(prov['cohort']['n']), '{:d}')
    mac('GseTwoZeroOneNineFourPos', int(prov['cohort']['events']), '{:d}')
    mac('GseTwoZeroOneNineFourOverlapN', int(ov['id_matches']), '{:d}')
    mac('GseTwoZeroOneNineFourUniqueN', len(uniq), '{:d}')
    mac('GseTwoZeroOneNineFourUniquePos', int(sub.pcr.sum()), '{:d}')
    mac('GseTwoZeroOneNineFourCarf', met.loc['carf', 'auroc'])
    mac('GseTwoZeroOneNineFourClinical', met.loc['clinical', 'auroc'])
    mac('GseTwoZeroOneNineFourStack', met.loc['stack', 'auroc'])
    mac('GseTwoZeroOneNineFourCarfLo', met.loc['carf', 'auroc_q025'])
    mac('GseTwoZeroOneNineFourCarfHi', met.loc['carf', 'auroc_q975'])
    mac('GseTwoZeroOneNineFourUniqueCarf', roc_auc_score(sub.pcr, sub['carf']))
    mac('GseTwoZeroOneNineFourUniqueClinical', roc_auc_score(sub.pcr, sub['clinical']))
    mac('GseTwoZeroOneNineFourUniqueStack', roc_auc_score(sub.pcr, sub['stack']))
    # RNA-corruption stress (experiments/results/e8_gse20194/stress.csv), CARF vs. clinical/stack.
    st = pd.read_csv(E8 / 'stress.csv').set_index(['scenario', 'model'])
    mac('GseTwoZeroOneNineFourDropoutCarf', st.loc[('rna_input_dropout50', 'carf'), 'auroc_mean'])
    mac('GseTwoZeroOneNineFourDropoutStack', st.loc[('rna_input_dropout50', 'stack'), 'auroc_mean'])
    mac('GseTwoZeroOneNineFourDropoutClinical', st.loc[('rna_input_dropout50', 'clinical'), 'auroc_mean'])


def write_macros():
    lines = ['% AUTO-GENERATED by carf3/make_assets_review.py -- do not edit by hand.']
    for k in sorted(MACROS):
        lines.append(f'\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{MACROS[k]}}}')
    (GEN / 'macros_review.tex').write_text('\n'.join(lines) + '\n')


def main():
    tab_anchor()
    tab_combo()
    tab_calib()
    fig_decision_curve()
    mrigate_macros()
    tab_gse20194()
    write_macros()
    print(f'Wrote {len(MACROS)} macros to {GEN / "macros_review.tex"}')


if __name__ == '__main__':
    main()
