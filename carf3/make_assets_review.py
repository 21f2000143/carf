HERE = Path(__file__).resolve().parent
RES = HERE / 'results' / 'review'
E8 = HERE.parent / 'experiments' / 'results' / 'e8_gse20194'  # read-only, pre-existing
TEX = HERE.parent / 'latex3'
GEN, FIG = TEX / 'generated', TEX / 'figures'
GEN.mkdir(parents=True, exist_ok=True); FIG.mkdir(parents=True, exist_ok=True)

NAMES = {'clinical': 'Clinical', 'mean': 'Mean', 'stack': 'Stacking', 'mask_stack': 'Mask-stacking',
        'offset_lr': 'Offset LR', 'robust_offset_lr': 'Robust offset LR', 'moddrop_mlp': 'ModDrop MLP',
        'carf2': 'CARF', 'carf2_no_gate': 'CARF w/o gate', 'gated_stack': 'Gated stacking',
        'gated_robust_offset_lr': 'Gated robust offset LR'}
MODELS = list(NAMES)
MACROS = {}
DIG = dict(zip('0123456789', ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine']))


def macname(name):
    """LaTeX control-word names cannot contain digits; spell them out, as in make_assets.py."""
    return ''.join(DIG.get(ch, ch) for ch in name)


def mac(name, value, fmt='{:.3f}'):
    v = fmt.format(value) if isinstance(value, (float, np.floating, int, np.integer)) and fmt else str(value)
    if isinstance(value, (float, np.floating, int, np.integer)) and value < 0 and fmt:
        v = f'\\ensuremath{{{v}}}'
    MACROS[macname(name)] = v


def corrected_ci(x, ratio=0.25):
    from scipy import stats
    x = np.asarray(x, float); n = len(x)
    m, s = x.mean(), x.std(ddof=1)
    se = s * np.sqrt(1 / n + ratio) if s > 0 else 1e-9
    t = stats.t.ppf(0.975, n - 1)
    return m, m - t * se, m + t * se


def bold(vals, nd=3):
    best = max(vals)
    return [('\\textbf{' + f'{{:.{nd}f}}'.format(v) + '}') if abs(v - best) < 1e-9 else f'{{:.{nd}f}}'.format(v)
            for v in vals]


# ------------------------------------------------------------------ anchor failure
def tab_anchor():
    df = pd.read_csv(RES / 'anchor_failure.csv')
    rows = ['\\begin{tabular}{l' + 'c' * len(MODELS) + '}', '\\toprule',
            'Scenario & ' + ' & '.join(NAMES[m] for m in MODELS) + ' \\\\', '\\midrule']
    label = {'anchor_hr_5': 'HR error, 5\\%', 'anchor_hr_20': 'HR error, 20\\%',
             'anchor_her2_5': 'HER2 error, 5\\%', 'anchor_her2_20': 'HER2 error, 20\\%',
             'anchor_hr_her2_5': 'HR+HER2 error, 5\\%', 'anchor_hr_her2_10': 'HR+HER2 error, 10\\%',
             'anchor_hr_her2_20': 'HR+HER2 error, 20\\%'}
    for sc, lab in label.items():
        g = df[df.scenario == sc].groupby('model').auroc.mean()
        vals = [g[m] for m in MODELS]
        rows.append(lab + ' & ' + ' & '.join(bold(vals)) + ' \\\\')
    rows += ['\\bottomrule', '\\end{tabular}']
    (GEN / 'tab_anchor.tex').write_text('% AUTO-GENERATED by carf3/make_assets_review.py\n' + '\n'.join(rows) + '\n')

    both20 = df[df.scenario == 'anchor_hr_her2_20'].pivot_table(index='rep', columns='model', values='auroc')
    both5 = df[df.scenario == 'anchor_hr_her2_5'].pivot_table(index='rep', columns='model', values='auroc')
    mac('AnchorBoth20Clinical', both20['clinical'].mean())
    mac('AnchorBoth20Carf', both20['carf2'].mean())
    mac('AnchorBoth20Stack', both20['stack'].mean())
    mac('AnchorBoth20RobustOffsetLr', both20['robust_offset_lr'].mean())
    mac('AnchorBoth20CarfNoGate', both20['carf2_no_gate'].mean())
    d1 = both20['carf2'] - both20['stack']
    m, lo, hi = corrected_ci(d1); mac('DAnchorBoth20CarfStack', m); mac('DAnchorBoth20CarfStackLo', lo); mac('DAnchorBoth20CarfStackHi', hi)
    d2 = both20['carf2'] - both20['carf2_no_gate']
    m, lo, hi = corrected_ci(d2); mac('DAnchorBoth20CarfNoGate', m); mac('DAnchorBoth20CarfNoGateLo', lo); mac('DAnchorBoth20CarfNoGateHi', hi)
    d3 = both5['carf2'] - both5['stack']
    m, lo, hi = corrected_ci(d3); mac('DAnchorBoth5CarfStack', m)
    mac('AnchorBoth5Carf', both5['carf2'].mean()); mac('AnchorBoth5Stack', both5['stack'].mean())


# ------------------------------------------------------------------ simultaneous failures
def tab_combo():
    df = pd.read_csv(RES / 'combo_failure.csv')
    label = {'rna_swap': 'RNA swap alone', 'mri_noisy': 'MRI noise alone',
             'rna_swap+mri_noise': 'RNA swap + MRI noise', 'rna_swap+mri_swap': 'RNA swap + MRI swap',
             'rna_dropout50': 'RNA dropout alone', 'mri_dropout60': 'MRI dropout alone',
             'rna_dropout+mri_dropout': 'RNA dropout + MRI dropout'}
    rows = ['\\begin{tabular}{l' + 'c' * len(MODELS) + '}', '\\toprule',
            'Scenario & ' + ' & '.join(NAMES[m] for m in MODELS) + ' \\\\', '\\midrule']
    for sc, lab in label.items():
        g = df[df.scenario == sc].groupby('model').auroc.mean()
        vals = [g[m] for m in MODELS]
        rows.append(lab + ' & ' + ' & '.join(bold(vals)) + ' \\\\')
        if sc in ('rna_swap', 'rna_dropout50'):
            rows.append('\\addlinespace')
    rows += ['\\bottomrule', '\\end{tabular}']
    (GEN / 'tab_combo.tex').write_text('% AUTO-GENERATED by carf3/make_assets_review.py\n' + '\n'.join(rows) + '\n')

    piv = {sc: df[df.scenario == sc].pivot_table(index='rep', columns='model', values='auroc')
           for sc in label}
    mac('ComboSwapNoiseCarf', piv['rna_swap+mri_noise']['carf2'].mean())
    mac('ComboSwapNoiseRobustOffsetLr', piv['rna_swap+mri_noise']['robust_offset_lr'].mean())
    mac('ComboSwapNoiseStack', piv['rna_swap+mri_noise']['stack'].mean())
    mac('ComboSwapSwapCarf', piv['rna_swap+mri_swap']['carf2'].mean())
    mac('ComboSwapSwapRobustOffsetLr', piv['rna_swap+mri_swap']['robust_offset_lr'].mean())
    mac('ComboSwapSwapStack', piv['rna_swap+mri_swap']['stack'].mean())
    mac('ComboDropoutCarf', piv['rna_dropout+mri_dropout']['carf2'].mean())
    mac('ComboDropoutRobustOffsetLr', piv['rna_dropout+mri_dropout']['robust_offset_lr'].mean())
    mac('SingleRnaSwapCarf', piv['rna_swap']['carf2'].mean())
    mac('SingleRnaSwapRobustOffsetLr', piv['rna_swap']['robust_offset_lr'].mean())
    for sc, key in [('rna_swap+mri_noise', 'SwapNoise'), ('rna_swap+mri_swap', 'SwapSwap'),
                    ('rna_dropout+mri_dropout', 'Dropout')]:
        d = piv[sc]['carf2'] - piv[sc]['robust_offset_lr']
        m, lo, hi = corrected_ci(d)
        mac(f'DCombo{key}CarfRobustOffsetLr', m)
        mac(f'DCombo{key}CarfRobustOffsetLrLo', lo)
        mac(f'DCombo{key}CarfRobustOffsetLrHi', hi)
    # Compounding: loss relative to intact under single vs combined failure, CARF vs best non-gated baseline.
    intact_auc = 0.849  # external CARF intact AUROC (from tab_main); kept consistent with main.tex macro IntCarfTwo? see note
    mac('ComboNoteIntact', intact_auc)


# ------------------------------------------------------------------ calibration + decision curve
def tab_calib():
    df = pd.read_csv(RES / 'calibration.csv')
    order = ['clinical', 'mean', 'stack', 'mask_stack', 'offset_lr', 'robust_offset_lr', 'moddrop_mlp',
            'carf2', 'carf2_no_gate', 'gated_stack', 'gated_robust_offset_lr']
    rows = ['\\begin{tabular}{lccccccc}', '\\toprule',
            'Model & \\multicolumn{3}{c}{Internal} & \\multicolumn{3}{c}{External} & \\\\',
            ' & Brier & ECE & Prev. & Brier & ECE & Prev. & \\\\', '\\midrule']
    for m in order:
        ri = df[(df.model == m) & (df.cohort == 'internal')].iloc[0]
        re = df[(df.model == m) & (df.cohort == 'external')].iloc[0]
        rows.append(f"{NAMES[m]} & {ri.brier_before:.3f}$\\to${ri.brier_after:.3f} & "
                    f"{ri.ece_before:.3f}$\\to${ri.ece_after:.3f} & {ri.prev_pred_before:.2f}$\\to${ri.prev_pred_after:.2f} & "
                    f"{re.brier_before:.3f}$\\to${re.brier_after:.3f} & {re.ece_before:.3f}$\\to${re.ece_after:.3f} & "
                    f"{re.prev_pred_before:.2f}$\\to${re.prev_pred_after:.2f} & \\\\")
    rows += ['\\bottomrule', '\\end{tabular}']
    (GEN / 'tab_calib_review.tex').write_text('% AUTO-GENERATED by carf3/make_assets_review.py\n' + '\n'.join(rows) + '\n')

    ci = df[(df.model == 'carf2') & (df.cohort == 'internal')].iloc[0]
    ce = df[(df.model == 'carf2') & (df.cohort == 'external')].iloc[0]
    for pfx, r in [('CalibIntCarf', ci), ('CalibExtCarf', ce)]:
        mac(f'{pfx}BrierBefore', r.brier_before); mac(f'{pfx}BrierAfter', r.brier_after)
        mac(f'{pfx}EceBefore', r.ece_before); mac(f'{pfx}EceAfter', r.ece_after)
        mac(f'{pfx}PrevBefore', r.prev_pred_before, '{:.2f}'); mac(f'{pfx}PrevAfter', r.prev_pred_after, '{:.2f}')
    mac('CalibTruePrev', ce.prev_true, '{:.2f}')


def fig_decision_curve():
    dc = pd.read_csv(RES / 'decision_curve.csv')
    fig, ax = plt.subplots(figsize=(8.2 / 2.54, 6.2 / 2.54))
    ax.plot(dc.threshold, dc.treat_all, '--', color='gray', label='Treat all')
    ax.plot(dc.threshold, dc.treat_none, ':', color='gray', label='Treat none')
    ax.plot(dc.threshold, dc['clinical'], label='Clinical', color='#1b9e77')
    ax.plot(dc.threshold, dc['stack'], label='Stacking', color='#d95f02')
    ax.plot(dc.threshold, dc['carf2'], label='CARF', color='#7570b3', linewidth=2)
    ax.set_xlabel('Threshold probability'); ax.set_ylabel('Net benefit')
    ax.legend(fontsize=7, frameon=False); ax.set_ylim(-0.05, 0.35)
    fig.tight_layout()
    fig.savefig(FIG / 'fig_decision_curve.pdf'); fig.savefig(FIG / 'fig_decision_curve.png', dpi=200)
    plt.close(fig)


